/**
 * Builds /knowledge/knowledge.md from src/content/content.ts. This is the
 * same passage list the Ask command bar searches in the browser, written
 * out so it can be reviewed in one place. Anything not in content.ts
 * cannot appear here and cannot be answered on the site.
 *
 * Run: npm run knowledge
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildPassages, sections } from "../src/content/content";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "../knowledge/knowledge.md");

const passages = buildPassages();
let md = `# Knowledge base for rachelcooray.com\n\nGenerated by scripts/export-knowledge.ts from src/content/content.ts. Do not edit by hand.\n\n`;

for (const s of sections) {
  const own = passages.filter((p) => p.section === s.id);
  if (own.length === 0) continue;
  md += `## ${s.number} ${s.label}\n\n`;
  for (const p of own) md += `**${p.title}**\n${p.text}\n\n`;
}

if (/—/.test(md)) throw new Error("Em dash found in generated knowledge. Fix content.ts.");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, md);
console.log(`Wrote ${outPath} (${passages.length} passages)`);
